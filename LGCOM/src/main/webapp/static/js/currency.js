function _getPrecision( currencyCode, extFlag ){
	
	if( CURRENCY[currencyCode] == undefined ) {
         alert("Currency Code mismatch!!!");
         return;
	}
	
    if( extFlag == undefined) {
    	return CURRENCY[currencyCode].prec;
    } else {
    	return CURRENCY[currencyCode].extPrec;;	
    }     
}

function _getCurrencyData() {
	var result = [];
	
	$.each( CURRENCY, function( key, value ){
		result.push({ code : key, name : key }); 
	});
	
	return result;
}